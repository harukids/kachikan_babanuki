const A =
  'stroke="#fff" fill="none" stroke-linecap="round" stroke-linejoin="round"';

function wrap(inner) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" fill="none">${inner}</svg>\n`;
}
function p(d, w = 10) {
  return `<path d="${d}" ${A} stroke-width="${w}"/>`;
}
function c(cx, cy, r, w = 5) {
  return `<circle cx="${cx}" cy="${cy}" r="${r}" ${A} stroke-width="${w}"/>`;
}
function l(x1, y1, x2, y2, w = 6) {
  return `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" ${A} stroke-width="${w}"/>`;
}
function spark(cx, cy, s = 16) {
  const h = s * 0.35;
  return p(
    `M${cx} ${cy - s} L${cx + h} ${cy - h} L${cx + s} ${cy} L${cx + h} ${cy + h} L${cx} ${cy + s} L${cx - h} ${cy + h} L${cx - s} ${cy} L${cx - h} ${cy - h} Z`,
    5,
  );
}
function dots(...pairs) {
  return pairs.map(([x, y, r = 6]) => c(x, y, r, 4)).join("");
}

