const stroke = (d, w = 10) =>
  `<path d="${d}" stroke="#fff" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round" fill="none"/>`;
const circle = (cx, cy, r, w = 10) =>
  `<circle cx="${cx}" cy="${cy}" r="${r}" stroke="#fff" stroke-width="${w}" fill="none"/>`;
const line = (x1, y1, x2, y2, w = 10) =>
  `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="#fff" stroke-width="${w}" stroke-linecap="round"/>`;
const poly = (points, w = 10) =>
  `<polygon points="${points}" stroke="#fff" stroke-width="${w}" stroke-linejoin="round" fill="none"/>`;

function wrap(inner) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" fill="none">${inner}</svg>\n`;
}

